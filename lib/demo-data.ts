function hr(pct: number | null, hit: number, total: number): HitRateBucket {
  return { pct, hit, total };
}

function vs(
  pct: number | null,
  hit: number,
  total: number,
  label: string,
  season: number,
  opponent: string,
): HitRateVsOpp {
  return { pct, hit, total, label, season, opponent };
}

interface PropSeed {
  id: string;
  player: string;
  team: string;
  market: string;
  line: string;
  price: number;
  hitRate: HitRateOut;
  book?: Theme | null;
  books?: PropOut["books"];
}

function prop(gameId: string, seed: PropSeed): PropOut {
  return {
    id: seed.id,
    player: seed.player,
    team: seed.team,
    market: seed.market,
    line: seed.line,
    price: seed.price,
    hitRate: seed.hitRate,
    selectionKey: propKey(gameId, seed.id),
    playerId: null,
    isSample: true,
    lineSource: "sample",
    hitRateSource: "sample",
    hitRateThroughWeek: 4,
    unlocked: true,
    locked: [],
    book: seed.book ?? null,
    books: seed.books ?? null,
  };
}

let gameSeq = 1;

function game(input: {
  id: string;
  away: string;
  home: string;
  kickoff: string;
  kickoffLabel: string;
  dateGroup: string;
  spread: [string, number, string, number];
  money: [number, number];
  total: [number, number, number];
  venue?: string;
  nflGameId: string;
  props: PropSeed[];
}): GameBoardOut {
  const [aLine, aPrice, hLine, hPrice] = input.spread;
  const spread: SpreadOut = {
    away: { line: aLine, price: aPrice },
    home: { line: hLine, price: hPrice },
  };
  const money: MoneyOut = { away: input.money[0], home: input.money[1] };
  const total: TotalOut = { line: input.total[0], over: input.total[1], under: input.total[2] };
  const n = gameSeq++;
  return {
    id: input.id,
    uuid: `00000000-0000-4000-8000-${n.toString(16).padStart(12, "0")}`,
    away: TEAM[input.away],
    home: TEAM[input.home],
    kickoff: input.kickoff,
    kickoffLabel: input.kickoffLabel,
    dateGroup: input.dateGroup,
    week: 5,
    season: 2026,
    seasonType: "REG",
    status: "scheduled",
    venue: input.venue ?? null,
    homeScore: null,
    awayScore: null,
    spread,
    money,
    total,
    nflGameId: input.nflGameId,
    source: "sample",
    linesSource: "sample",
    isSampleLines: true,
    props: input.props.map((seed) => prop(input.id, seed)),
  };
}

